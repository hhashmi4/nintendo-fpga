#!/usr/bin/env python3
"""Generate Phase 5M diagnostic constants from the versioned JSON contract."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[1]
CONTRACT_PATH = ROOT / "config" / "diagnostic_mmio.json"
SV_PATH = ROOT / "rtl" / "diagnostic" / "nes_diagnostic_mmio_pkg.sv"
PY_PATH = ROOT / "software" / "nes_debug" / "mmio_registers.py"
TCL_PATH = ROOT / "quartus" / "nes_diagnostic_mmio_map.tcl"


def number(value: int | str) -> int:
    return int(value, 0) if isinstance(value, str) else value


def load_contract() -> dict[str, object]:
    return json.loads(CONTRACT_PATH.read_text(encoding="utf-8"))


def sv_hex(width: int, value: int) -> str:
    return f"{width}'h{value:0{(width + 3) // 4}x}"


def render_sv(contract: dict[str, object]) -> str:
    registers = contract["registers"]
    capabilities = contract["capabilities"]
    availability = contract["availability"]
    controls = contract["control_bits"]
    faults = contract["faults"]
    events = contract["events"]
    reset_causes = contract["reset_causes"]
    assert all(isinstance(item, dict) for item in (
        registers, capabilities, availability, controls, faults, events,
        reset_causes,
    ))
    capability_word = sum(1 << number(bit) for bit in capabilities.values())
    availability_word = sum(
        1 << number(bit)
        for name, bit in availability.items()
        if name != "CPU_INSTRUCTIONS"
    )
    lines = [
        "`timescale 1ns/1ps",
        "",
        "// Generated by scripts/generate_diagnostic_mmio_defs.py.",
        "// Edit config/diagnostic_mmio.json, not this file.",
        "package nes_diagnostic_mmio_pkg;",
        f"    localparam logic [31:0] DIAG_MAGIC = {sv_hex(32, number(contract['magic']))};",
        f"    localparam logic [31:0] DIAG_VERSION = {sv_hex(32, (number(contract['version_major']) << 16) | number(contract['version_minor']))};",
        f"    localparam logic [31:0] DIAG_BUILD_ID = {sv_hex(32, number(contract['build_id']))};",
        f"    localparam logic [31:0] DIAG_CAPABILITIES = {sv_hex(32, capability_word)};",
        f"    localparam logic [31:0] DIAG_AVAILABILITY = {sv_hex(32, availability_word)};",
        f"    localparam integer DIAG_SPAN_BYTES = {number(contract['span_bytes'])};",
        f"    localparam integer DIAG_TRACE_DEPTH = {number(contract['trace_depth'])};",
        f"    localparam logic [31:0] DIAG_HPS_WINDOW_BASE = {sv_hex(32, number(contract['hps_lightweight_window_base']))};",
        f"    localparam logic [31:0] DIAG_SLAVE_OFFSET = {sv_hex(32, number(contract['slave_offset']))};",
        "    localparam logic [31:0] DIAG_PHYSICAL_BASE =",
        "        DIAG_HPS_WINDOW_BASE + DIAG_SLAVE_OFFSET;",
        "",
    ]
    for name, value in registers.items():
        lines.append(
            f"    localparam logic [8:0] DIAG_REG_{name} = {sv_hex(9, number(value))};"
        )
    lines.append("")
    for name, bit in controls.items():
        lines.append(f"    localparam integer DIAG_CONTROL_{name}_BIT = {number(bit)};")
    lines.append("")
    for name, code in faults.items():
        lines.append(f"    localparam logic [7:0] DIAG_FAULT_{name} = 8'd{number(code)};")
        lines.append(f"    localparam integer DIAG_FAULT_{name}_BIT = {number(code) - 1};")
    lines.append("")
    for name, code in events.items():
        lines.append(f"    localparam logic [7:0] DIAG_EVENT_{name} = 8'd{number(code)};")
    lines.append("")
    for name, code in reset_causes.items():
        lines.append(f"    localparam logic [7:0] DIAG_RESET_{name} = 8'd{number(code)};")
    lines.extend(["endpackage", ""])
    return "\n".join(lines)


def render_python(contract: dict[str, object]) -> str:
    capabilities = contract["capabilities"]
    availability = contract["availability"]
    window = number(contract["hps_lightweight_window_base"])
    offset = number(contract["slave_offset"])
    capability_word = sum(1 << number(bit) for bit in capabilities.values())
    availability_word = sum(
        1 << number(bit)
        for name, bit in availability.items()
        if name != "CPU_INSTRUCTIONS"
    )
    lines = [
        '"""Generated Phase 5M constants; edit config/diagnostic_mmio.json."""',
        "",
        "# Generated by scripts/generate_diagnostic_mmio_defs.py.",
        f"MMIO_MAGIC = 0x{number(contract['magic']):08X}",
        f"MMIO_VERSION_MAJOR = {number(contract['version_major'])}",
        f"MMIO_VERSION_MINOR = {number(contract['version_minor'])}",
        "MMIO_VERSION = (MMIO_VERSION_MAJOR << 16) | MMIO_VERSION_MINOR",
        f"MMIO_BUILD_ID = 0x{number(contract['build_id']):08X}",
        f"MMIO_CAPABILITIES = 0x{capability_word:08X}",
        f"MMIO_AVAILABILITY = 0x{availability_word:08X}",
        f"MMIO_HPS_WINDOW_BASE = 0x{window:08X}",
        f"MMIO_SLAVE_OFFSET = 0x{offset:08X}",
        "MMIO_PHYSICAL_BASE = MMIO_HPS_WINDOW_BASE + MMIO_SLAVE_OFFSET",
        f"MMIO_SPAN_BYTES = {number(contract['span_bytes'])}",
        f"TRACE_DEPTH = {number(contract['trace_depth'])}",
        "",
    ]
    for name, value in contract["registers"].items():
        lines.append(f"REG_{name} = 0x{number(value):03X}")
    lines.extend(["", "REGISTER_OFFSETS = {"])
    lines.extend(
        f"    {name!r}: REG_{name}," for name in contract["registers"]
    )
    lines.append("}")
    for group_name, prefix in (
        ("capabilities", "CAP"),
        ("availability", "AVAILABLE"),
        ("control_bits", "CONTROL"),
    ):
        lines.append("")
        for name, bit in contract[group_name].items():
            lines.append(f"{prefix}_{name} = 1 << {number(bit)}")
    for group_name, prefix in (
        ("faults", "FAULT"),
        ("events", "EVENT"),
        ("reset_causes", "RESET_CAUSE"),
    ):
        lines.append("")
        for name, code in contract[group_name].items():
            lines.append(f"{prefix}_{name} = {number(code)}")
    lines.extend([
        "",
        "FAULT_NAMES = {",
        *(f"    FAULT_{name}: {name!r}," for name in contract["faults"]),
        "}",
        "FAULT_BITS = {code: 1 << (code - 1) for code in FAULT_NAMES}",
        "EVENT_NAMES = {",
        *(f"    EVENT_{name}: {name!r}," for name in contract["events"]),
        "}",
        "RESET_CAUSE_NAMES = {",
        *(f"    RESET_CAUSE_{name}: {name!r}," for name in contract["reset_causes"]),
        "}",
        "",
    ])
    return "\n".join(lines)


def render_tcl(contract: dict[str, object]) -> str:
    return "\n".join([
        "# Generated by scripts/generate_diagnostic_mmio_defs.py.",
        "# Edit config/diagnostic_mmio.json, not this file.",
        f"set NES_DIAGNOSTIC_MMIO_HPS_WINDOW_BASE 0x{number(contract['hps_lightweight_window_base']):08x}",
        f"set NES_DIAGNOSTIC_MMIO_SLAVE_OFFSET 0x{number(contract['slave_offset']):08x}",
        f"set NES_DIAGNOSTIC_MMIO_SPAN_BYTES {number(contract['span_bytes'])}",
        "",
    ])


def update(path: Path, content: str, check: bool) -> bool:
    current = path.read_text(encoding="utf-8") if path.exists() else None
    if current == content:
        return True
    if check:
        print(f"out of date: {path.relative_to(ROOT)}", file=sys.stderr)
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return True


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    contract = load_contract()
    results = [
        update(SV_PATH, render_sv(contract), args.check),
        update(PY_PATH, render_python(contract), args.check),
        update(TCL_PATH, render_tcl(contract), args.check),
    ]
    return 0 if all(results) else 1


if __name__ == "__main__":
    raise SystemExit(main())
