#!/usr/bin/env python3
"""Generate stable JSON and Markdown views of the official opcode matrix."""

import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from verification.cpu_coverage import OFFICIAL_OPCODE_COVERAGE  # noqa: E402


JSON_PATH = ROOT / "docs" / "cpu-official-opcodes.json"
MARKDOWN_PATH = ROOT / "docs" / "cpu-official-opcode-matrix.md"


def main() -> None:
    JSON_PATH.write_text(
        json.dumps(OFFICIAL_OPCODE_COVERAGE, indent=2) + "\n",
        encoding="utf-8",
    )
    header = (
        "# Official Ricoh 2A03 opcode matrix\n\n"
        "Generated by `scripts/generate_cpu_opcode_matrix.py`; "
        "do not edit by hand. All rows are official NMOS 6502 bytes supported "
        "by the Ricoh 2A03 CPU subset.\n\n"
        "| Opcode | Instruction | Mode | Bytes | Cycles | Page + | Branch + | "
        "Branch page + | Class | Flags | Status |\n"
        "|---:|---|---|---:|---:|---:|---:|---:|---|---|---|\n"
    )
    lines = [header]
    for row in OFFICIAL_OPCODE_COVERAGE:
        lines.append(
            f"| `${row['opcode']}` | {row['instruction']} | "
            f"{row['addressing_mode']} | {row['bytes']} | "
            f"{row['base_cycles']} | {row['page_cross_penalty']} | "
            f"{row['branch_taken_penalty']} | "
            f"{row['branch_page_cross_penalty']} | "
            f"{row['functional_class']} | {row['flag_effects']} | "
            f"{row['implementation_status']}/{row['test_status']} |\n"
        )
    MARKDOWN_PATH.write_text("".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
