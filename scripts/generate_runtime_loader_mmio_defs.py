#!/usr/bin/env python3
"""Generate the shared Phase 4F-F MMIO definitions from one JSON contract."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[1]
CONTRACT_PATH = ROOT / "config" / "runtime_loader_mmio.json"
SV_PATH = ROOT / "rtl" / "loader" / "nes_runtime_loader_mmio_pkg.sv"
PY_PATH = ROOT / "software" / "nes_loader" / "mmio_registers.py"
TCL_PATH = ROOT / "quartus" / "nes_runtime_loader_mmio_map.tcl"


def number(value: int | str) -> int:
    return int(value, 0) if isinstance(value, str) else value


def load_contract() -> dict[str, object]:
    return json.loads(CONTRACT_PATH.read_text(encoding="utf-8"))


def sv_hex(width: int, value: int) -> str:
    digits = (width + 3) // 4
    return f"{width}'h{value:0{digits}x}"


def render_sv(contract: dict[str, object]) -> str:
    registers = contract["registers"]
    capabilities = contract["capabilities"]
    status_bits = contract["status_bits"]
    manifest_fields = contract["manifest_fields"]
    control_bits = contract["control_bits"]
    assert isinstance(registers, dict)
    assert isinstance(capabilities, dict)
    assert isinstance(status_bits, dict)
    assert isinstance(manifest_fields, dict)
    assert isinstance(control_bits, dict)
    capability_word = sum(1 << number(bit) for bit in capabilities.values())
    lines = [
        "`timescale 1ns/1ps",
        "",
        "// Generated by scripts/generate_runtime_loader_mmio_defs.py.",
        "// Edit config/runtime_loader_mmio.json, not this file.",
        "package nes_runtime_loader_mmio_pkg;",
        f"    localparam logic [31:0] MMIO_MAGIC = {sv_hex(32, number(contract['magic']))};",
        f"    localparam logic [15:0] MMIO_VERSION_MAJOR = {sv_hex(16, number(contract['version_major']))};",
        f"    localparam logic [15:0] MMIO_VERSION_MINOR = {sv_hex(16, number(contract['version_minor']))};",
        "    localparam logic [31:0] MMIO_VERSION =",
        "        {MMIO_VERSION_MAJOR, MMIO_VERSION_MINOR};",
        f"    localparam logic [31:0] MMIO_CAPABILITIES = {sv_hex(32, capability_word)};",
        f"    localparam integer MMIO_SPAN_BYTES = {number(contract['span_bytes'])};",
        f"    localparam logic [31:0] MMIO_HPS_WINDOW_BASE = {sv_hex(32, number(contract['hps_lightweight_window_base']))};",
        f"    localparam logic [31:0] MMIO_SLAVE_OFFSET = {sv_hex(32, number(contract['slave_offset']))};",
        "    localparam logic [31:0] MMIO_PHYSICAL_BASE =",
        "        MMIO_HPS_WINDOW_BASE + MMIO_SLAVE_OFFSET;",
        "",
    ]
    for name, value in registers.items():
        lines.append(
            f"    localparam logic [5:0] MMIO_REG_{name} = {sv_hex(6, number(value))};"
        )
    lines.append("")
    for name, bit in capabilities.items():
        lines.append(f"    localparam integer MMIO_CAP_{name}_BIT = {number(bit)};")
    lines.append("")
    for name, bit in status_bits.items():
        lines.append(f"    localparam integer MMIO_STATUS_{name}_BIT = {number(bit)};")
    lines.extend(
        [
            f"    localparam integer MMIO_STATUS_STATE_SHIFT = {number(contract['status_state_shift'])};",
            f"    localparam integer MMIO_STATUS_STATE_WIDTH = {number(contract['status_state_width'])};",
            "",
            f"    localparam integer MMIO_ERROR_CODE_SHIFT = {number(contract['error_code_shift'])};",
            f"    localparam integer MMIO_ERROR_CODE_WIDTH = {number(contract['error_code_width'])};",
            f"    localparam integer MMIO_ERROR_SUBMIT_REJECTED_BIT = {number(contract['error_submit_rejected_bit'])};",
            f"    localparam integer MMIO_ERROR_RESPONSE_FAILED_BIT = {number(contract['error_response_failed_bit'])};",
            f"    localparam integer MMIO_ERROR_STATE_SHIFT = {number(contract['error_state_shift'])};",
            f"    localparam integer MMIO_ERROR_STATE_WIDTH = {number(contract['error_state_width'])};",
            "",
        ]
    )
    for name, value in manifest_fields.items():
        lines.append(f"    localparam integer MMIO_MANIFEST_{name} = {number(value)};")
    lines.append("")
    for name, bit in control_bits.items():
        lines.append(f"    localparam integer MMIO_CONTROL_{name}_BIT = {number(bit)};")
    lines.extend(["endpackage", ""])
    return "\n".join(lines)


def render_python(contract: dict[str, object]) -> str:
    registers = contract["registers"]
    capabilities = contract["capabilities"]
    status_bits = contract["status_bits"]
    manifest_fields = contract["manifest_fields"]
    control_bits = contract["control_bits"]
    assert isinstance(registers, dict)
    assert isinstance(capabilities, dict)
    assert isinstance(status_bits, dict)
    assert isinstance(manifest_fields, dict)
    assert isinstance(control_bits, dict)
    capability_word = sum(1 << number(bit) for bit in capabilities.values())
    window = number(contract["hps_lightweight_window_base"])
    offset = number(contract["slave_offset"])
    lines = [
        '"""Generated Phase 4F-F MMIO constants; edit the JSON contract."""',
        "",
        "# Generated by scripts/generate_runtime_loader_mmio_defs.py.",
        f"MMIO_MAGIC = 0x{number(contract['magic']):08X}",
        f"MMIO_VERSION_MAJOR = {number(contract['version_major'])}",
        f"MMIO_VERSION_MINOR = {number(contract['version_minor'])}",
        "MMIO_VERSION = (MMIO_VERSION_MAJOR << 16) | MMIO_VERSION_MINOR",
        f"MMIO_CAPABILITIES = 0x{capability_word:08X}",
        f"MMIO_HPS_WINDOW_BASE = 0x{window:08X}",
        f"MMIO_SLAVE_OFFSET = 0x{offset:08X}",
        "MMIO_PHYSICAL_BASE = MMIO_HPS_WINDOW_BASE + MMIO_SLAVE_OFFSET",
        f"MMIO_SPAN_BYTES = {number(contract['span_bytes'])}",
        "",
    ]
    for name, value in registers.items():
        lines.append(f"REG_{name} = 0x{number(value):02X}")
    lines.append("")
    for name, bit in capabilities.items():
        lines.append(f"CAP_{name} = 1 << {number(bit)}")
    lines.append("")
    for name, bit in status_bits.items():
        lines.append(f"STATUS_{name} = 1 << {number(bit)}")
    lines.extend(
        [
            f"STATUS_STATE_SHIFT = {number(contract['status_state_shift'])}",
            f"STATUS_STATE_MASK = {(1 << number(contract['status_state_width'])) - 1} << STATUS_STATE_SHIFT",
            "",
            f"ERROR_CODE_SHIFT = {number(contract['error_code_shift'])}",
            f"ERROR_CODE_MASK = {(1 << number(contract['error_code_width'])) - 1} << ERROR_CODE_SHIFT",
            f"ERROR_SUBMIT_REJECTED = 1 << {number(contract['error_submit_rejected_bit'])}",
            f"ERROR_RESPONSE_FAILED = 1 << {number(contract['error_response_failed_bit'])}",
            f"ERROR_STATE_SHIFT = {number(contract['error_state_shift'])}",
            f"ERROR_STATE_MASK = {(1 << number(contract['error_state_width'])) - 1} << ERROR_STATE_SHIFT",
            "",
        ]
    )
    for name, value in manifest_fields.items():
        suffix = "SHIFT" if name.endswith("SHIFT") else "WIDTH"
        lines.append(f"MANIFEST_{name} = {number(value)}")
        if suffix == "WIDTH":
            stem = name.removesuffix("_WIDTH")
            lines.append(
                f"MANIFEST_{stem}_MASK = {(1 << number(value)) - 1} << MANIFEST_{stem}_SHIFT"
            )
    lines.append("")
    for name, bit in control_bits.items():
        lines.append(f"CONTROL_{name} = 1 << {number(bit)}")
    lines.append("")
    return "\n".join(lines)


def render_tcl(contract: dict[str, object]) -> str:
    return "\n".join(
        [
            "# Generated by scripts/generate_runtime_loader_mmio_defs.py.",
            "# Edit config/runtime_loader_mmio.json, not this file.",
            f"set NES_LOADER_MMIO_HPS_WINDOW_BASE 0x{number(contract['hps_lightweight_window_base']):08x}",
            f"set NES_LOADER_MMIO_SLAVE_OFFSET 0x{number(contract['slave_offset']):08x}",
            f"set NES_LOADER_MMIO_SPAN_BYTES {number(contract['span_bytes'])}",
            "",
        ]
    )


def update(path: Path, content: str, check: bool) -> bool:
    current = path.read_text(encoding="utf-8") if path.exists() else None
    if current == content:
        return True
    if check:
        print(f"out of date: {path.relative_to(ROOT)}", file=sys.stderr)
        return False
    path.write_text(content, encoding="utf-8")
    return True


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    contract = load_contract()
    results = [
        update(SV_PATH, render_sv(contract), args.check),
        update(PY_PATH, render_python(contract), args.check),
        update(TCL_PATH, render_tcl(contract), args.check),
    ]
    return 0 if all(results) else 1


if __name__ == "__main__":
    raise SystemExit(main())
