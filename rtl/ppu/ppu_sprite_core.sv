        .sprite_overflow_set         (sprite_overflow_set),
        .evaluation_phase            (sprite_evaluation_phase),
        .evaluation_sprite_index     (sprite_evaluation_index),
        .evaluation_byte_index       (sprite_evaluation_byte),
        .evaluation_relative_row     (sprite_evaluation_relative_row),
        .sprite_height               (sprite_height),
        .primary_read_address        (primary_oam_read_address),
        .primary_read_data           (primary_oam_read_data),
        .secondary_clear_write       (secondary_clear_write),
        .secondary_evaluation_write  (secondary_evaluation_write),
        .secondary_write_address     (secondary_write_address),
        .secondary_write_data        (secondary_write_data),
        .evaluation_done             (sprite_evaluation_done)
    );
