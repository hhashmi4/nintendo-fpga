    function automatic logic [7:0] debug_hex_char(input logic [3:0] nibble);
        if (nibble < 4'd10)
            debug_hex_char = 8'h30 + {4'b0000, nibble};
        else
            debug_hex_char = 8'h41 + {4'b0000, (nibble - 4'd10)};
    endfunction

    function automatic logic [7:0] debug_bit_char(input logic value);
        debug_bit_char = value ? 8'h31 : 8'h30;
    endfunction

    function automatic logic debug_font_supported(input logic [7:0] character);
        debug_font_supported =
            (character == 8'h20) ||
            ((character >= 8'h30) && (character <= 8'h39)) ||
            ((character >= 8'h41) && (character <= 8'h5a)) ||
            (character == 8'h2e) || (character == 8'h2d) ||
            (character == 8'h2f) || (character == 8'h3a) ||
            (character == 8'h3d) || (character == 8'h5b) ||
            (character == 8'h5d);
    endfunction

